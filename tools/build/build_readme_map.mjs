/*
===============================================================================

	build_readme_map.mjs

	A small, deterministic source-derived plate for the field manual.
	Connections are resolved static calls, not an execution order or benchmark.

===============================================================================
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root = fileURLToPath( new URL( '../../', import.meta.url ) );
const input = fs.readFileSync( path.join( root, 'docs/execution_map.json' ) );
const inventory = JSON.parse( input );
const names = ['main', 'Main_StartGame', 'Com_Init', 'Com_InitGraphics', 'Com_InitListenGraphics', 'CL_Init', 'SCR_MenuInit', 'S_Init', 'SCR_InitGpu'];
const nodes = names.map( name => {
	const matches = inventory.functions.filter( row => row.name === name );
	if ( matches.length !== 1 ) throw new Error( `Ambiguous/missing atlas function: ${name}` );
	return matches[0];
} );
const ids = new Map( nodes.map( ( row, i ) => [row.id, `n${i}`] ) );
const graph = nodes.map( row => `  ${ids.get( row.id )}["${row.name}"]` );
let edges = 0;
for ( const row of nodes ) for ( const target of row.calls ) if ( ids.has( target ) ) {
	graph.push( `  ${ids.get( row.id )} --> ${ids.get( target )}` ); edges++;
}
const hash = createHash( 'sha256' ).update( input ).digest( 'hex' );
const lines = [
	'# Operations map / first-frame entry points', '',
	'<!-- Generated by npm run docs:map. Do not edit this file by hand. -->', '',
	'**View: resolved static function calls.** This is a curated subset of the engine inventory, not the complete loader graph. Edges do not establish timing, conditional execution, or the order of awaited work. The browser launcher and workers are outside this inventory.', '',
	'```mermaid', 'flowchart LR', ...graph, '```', '',
	`This plate has **${nodes.length} functions and ${edges} resolved edges**. The full inventory contains ${inventory.stats.functions} functions across ${inventory.stats.files} analyzed files, ${inventory.stats.resolvedCallEdges} resolved call edges and ${inventory.stats.unresolvedIdentifierCalls} unresolved identifier calls. Unresolved calls are not guessed.`, '',
	'| Function | Source definition |', '| --- | --- |',
	...nodes.map( row => `| \`${row.name}\` | [${row.file}:${row.line}](../${row.file}#L${row.line}) |` ), '',
	'## Reproduce the plate', '', '```sh', 'npm run exec:map', 'npm run docs:map', 'npm run verify:docs', '```', '',
	`Inventory SHA-256: \`${hash}\`. No clock time, machine name, retail asset or absolute filesystem path is embedded.`, '',
	'[Full call inventory](execution_map.json) · [Execution contract](EXECUTION_MAP.md) · [Loading architecture](LOADING-ARCHITECTURE.md) · [README](../README.md)', '',
];
const output = lines.join( '\n' );
const target = path.join( root, 'docs/OPERATIONS-MAP.md' );
if ( process.argv.includes( '--write' ) ) { fs.writeFileSync( target, output ); console.log( 'Operations map updated.' ); }
else if ( !fs.existsSync( target ) || fs.readFileSync( target, 'utf8' ) !== output ) throw new Error( 'Stale operations map. Run npm run docs:map and commit the result.' );
else console.log( 'Operations map matches the source inventory.' );
